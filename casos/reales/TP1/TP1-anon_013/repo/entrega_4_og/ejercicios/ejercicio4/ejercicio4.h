

#ifndef EJERCICIO4_H
#define EJERCICIO4_H
/**
 * Función que calcula el máximo común divisor entre dos números
 * @param primer_numero
 * @param segundo_numero
 * @return el máximo común divisor
 * @pre primer_numero != 0 o segundo_numero != 0
 */
int maximo_comun_divisor(int primer_numero, int segundo_numero);

/**
 * Función que calcula el mínimo común múltiplo entre dos números
 * @param primer_numero
 * @param segundo_numero
 * @return el mínimo común múltiplo
 * @pre primer_numero > 0 y segundo_numero > 0
 */
int minimo_comun_multiplo(int primer_numero, int segundo_numero);
#endif

